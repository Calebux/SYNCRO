#!/usr/bin/env node
// Generates docs/api-reference/errors.mdx from the gateway error taxonomy.
// Usage:
//   node scripts/generate-error-docs.mjs          # write the docs page
//   node scripts/generate-error-docs.mjs --check  # fail if the page is out of date

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const taxonomyPath = resolve(repoRoot, "backend/src/errors/gateway-taxonomy.json");
const outputPath = resolve(repoRoot, "docs/api-reference/errors.mdx");

const checkMode = process.argv.includes("--check");

function loadTaxonomy() {
  const raw = readFileSync(taxonomyPath, "utf8");
  const parsed = JSON.parse(raw);
  const codes = Array.isArray(parsed) ? parsed : parsed.codes ?? parsed.errors ?? [];
  if (!Array.isArray(codes) || codes.length === 0) {
    throw new Error(`No error codes found in ${taxonomyPath}`);
  }
  return codes;
}

function escapeCell(value) {
  if (value === undefined || value === null || value === "") return "—";
  return String(value).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function render(codes) {
  const sorted = [...codes].sort((a, b) => {
    const sa = Number(a.status ?? a.httpStatus ?? 0);
    const sb = Number(b.status ?? b.httpStatus ?? 0);
    if (sa !== sb) return sa - sb;
    return String(a.code ?? "").localeCompare(String(b.code ?? ""));
  });

  const lines = [];
  lines.push("---");
  lines.push("title: Error codes");
  lines.push("description: Reference of every error code returned by the gateway.");
  lines.push("---");
  lines.push("");
  lines.push("{/* This file is generated by scripts/generate-error-docs.mjs. Do not edit by hand. */}");
  lines.push("");
  lines.push("Every error response from the gateway includes a stable `code` field. Use the table below to map a code to its HTTP status, the cause, and the recommended remedy.");
  lines.push("");
  lines.push("| Code | HTTP status | Cause | Remedy |");
  lines.push("| --- | --- | --- | --- |");
  for (const entry of sorted) {
    const code = escapeCell(entry.code);
    const status = escapeCell(entry.status ?? entry.httpStatus);
    const cause = escapeCell(entry.cause ?? entry.description ?? entry.message);
    const remedy = escapeCell(entry.remedy ?? entry.resolution ?? entry.action);
    lines.push(`| \`${code}\` | ${status} | ${cause} | ${remedy} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  const codes = loadTaxonomy();
  const output = render(codes);

  if (checkMode) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
    if (current !== output) {
      console.error(
        `docs/api-reference/errors.mdx is out of date. Run \`node scripts/generate-error-docs.mjs\` and commit the result.`
      );
      process.exit(1);
    }
    console.log("docs/api-reference/errors.mdx is up to date.");
    return;
  }

  writeFileSync(outputPath, output, "utf8");
  console.log(`Wrote ${codes.length} error codes to docs/api-reference/errors.mdx`);
}

main();
